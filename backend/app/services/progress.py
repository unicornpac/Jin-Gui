def classify_response(response: str) -> str:
    """根据 AI 回复内容分类消息类型"""
    if not response:
        return "question"
    r = response[:100]
    if any(k in r for k in ["评价", "总结", "评分", "成绩", "训练结束"]):
        return "evaluation"
    if any(k in r for k in ["正确", "很好", "不错", "非常棒", "答对了"]):
        return "praise"
    if any(k in r for k in ["提示", "再想想", "注意", "考虑一下"]):
        return "hint"
    return "question"


