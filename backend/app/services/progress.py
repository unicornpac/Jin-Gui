# 疑问句的特征：句末语气词/问号，或句首的疑问结构
_QUESTION_TAIL = ("？", "?", "吗", "呢")
_QUESTION_HEAD = (
    "是不是", "是否", "有没有", "会不会", "像不像", "能不能", "要不要", "可不可以",
    "什么", "怎么", "如何", "为什么", "哪",
)
# 只有明确的判断性否定才算；「无力」「无汗」这类症状描述不能进这张表
_NEGATION = ("不是", "不属", "并非", "不像", "排除", "不支持", "不代表", "不能说")

_SENTENCE_END = re.compile(r"(?<=[。！？!?；;\n])")


def _has_negation(sentence: str) -> bool:
    return any(marker in sentence for marker in _NEGATION)


def _is_question(sentence: str) -> bool:
    if sentence.endswith(_QUESTION_TAIL):
        return True
    return any(sentence.startswith(marker) for marker in _QUESTION_HEAD)


def statement_text(text: str) -> str:
    """只保留学生的**陈述句**，剔除问句与否定句。

    进度判定关心的是「学生有没有做出判断」，而不是「有没有出现关键词」。
    「是不是少阳病？」「不像少阳」都含关键词，但都不是判断——

    - 问句：整句丢弃（"你是不是少阳病？"）
    - 否定句：按逗号拆开，只丢掉带否定的分句（"不像少阳，应该是太阳病"
      保留后半句的「太阳病」）
    """
    if not text:
        return ""
    kept: List[str] = []
    for sentence in _SENTENCE_END.split(text):
        sentence = sentence.strip()
        if not sentence or _is_question(sentence):
            continue
        if _has_negation(sentence):
            for part in re.split(r"[，,、]", sentence):
                part = part.strip()
                if part and not _has_negation(part) and not _is_question(part):
                    kept.append(part)
        else:
            kept.append(sentence)
    return " ".join(kept)


# 各难度到哪一步就算走完。初级只要求辨病，中级到析证，高级才走满四阶段。
# 之前统一要求「四阶段全完成」，初一学生永远达不到，只能靠轮数上限硬撑。
LEVEL_STAGES = {
    "初级": ("辨病",),
    "中级": ("辨病", "平脉", "析证"),
    "高级": tuple(STAGE_KEYS),
}

# 各难度的对话轮数上限：初级问几句就该收尾，高级允许长程推演
LEVEL_TURN_LIMIT = {"初级": 15, "中级": 30, "高级": 50}

# 辨病连续答错这么多次就结束会话
MAX_WRONG_DIAGNOSIS = 3


def should_end_session(turn_count: int, progress: dict, level: str) -> bool:
    """判断是否应自动结束会话。

    结束条件（满足其一）：
    1. **当前难度要求的阶段**全部完成——初级只看辨病，中级看辨病/平脉/析证，
       高级才要求四阶段齐全；
    2. 交互轮数达到该难度的上限。

    `turn_count` 必须是会话的真实消息总数。此前传的是给模型的上下文窗口
    （`_get_history_messages(limit=20)`），最多 20 条，中级 30、高级 50 的
    上限永远触发不了。
    """
    # 初级：辨病连错三次直接结束（没有后续关卡可走）
    # 中高级不在这里结束——它们由调用方「公布答案 + 强制过关」处理
    if (level == "初级"
            and int(progress.get("wrong_diagnosis_count") or 0) >= MAX_WRONG_DIAGNOSIS):
        return True

    stages = LEVEL_STAGES.get(level, tuple(STAGE_KEYS))
    if progress and all(progress.get(stage) for stage in stages):
        return True
    return turn_count >= LEVEL_TURN_LIMIT.get(level, SESSION_TURN_LIMIT)


def build_progress_hint(progress: dict) -> str:
    """根据后端识别的实际进度，生成患者行为指令"""
    hints = []
    if progress.get('辨病'):
        # 这一条是硬指令：模型此前会在学生说出病名后继续反问「我不太懂，您说我是啥毛病」，
        # 学生完全不知道自己说对了没有。
        hints.append(
            '- 辨病阶段已完成：医生已经说中了你的病。**本轮第一句必须确认被说中**，'
            '用患者的口语，例如「对对，就是这毛病」「嗯，你算是说着了」「是这么回事」。'
            '禁止反问（不要说「我不太懂」「您说我是啥毛病」），禁止继续追问症状。'
            '确认之后可以补一句"这毛病能治好不""要吃多久"，自然往收尾走。'
        )
    if progress.get('平脉'):
        hints.append('- 平脉阶段已完成：医生连你的脉象都说对了。你更信任他了——语气放松，怀疑感减少，更愿意透露兼症和生活细节。')
    if progress.get('析证'):
        hints.append('- 析证阶段已完成：医生分析得很透彻。你表现出"终于有人懂我"的释然感，态度完全配合，有问必答。')
    if progress.get('定治'):
        hints.append('- 定治阶段已完成：你完全信任医生。可以说"行那我听你的""要多久好转？"之类的话，自然进入收尾。')
    if not hints:
        return ''
    return '## 当前进度行为指令（医生已达到的进度，据此调整你的态度）\n' + '\n'.join(hints)


# ==================== 分关卡判定 ====================

LEVEL_ORDER = {"初级": 0, "中级": 1, "高级": 2}

STAGE_SEQUENCE = {
    "初级": ("辨病",),
    "中级": ("辨病", "平脉", "析证"),
    "高级": ("辨病", "平脉", "析证", "定治"),
}

# 各关「学生明显在答这一关」的触发词：出现这些说明他在表态，只是没答对
STAGE_ATTEMPT_WORDS = {
    "平脉": ("脉", "主", "提示", "说明"),
    "析证": ("病机", "因为", "由于", "导致", "所以", "鉴别", "区别"),
    "定治": ("治", "方", "汤", "宜", "当用"),
}


def stage_points(case, stage: str, level: str) -> list:
    """该关在当前难度下要求答到的要点（取 min_level <= 当前难度）。"""
    order = LEVEL_ORDER.get(level, 0)
    return [
        p for p in (getattr(case, "scoring_points", None) or [])
        if p.get("stage") == stage and LEVEL_ORDER.get(p.get("min_level"), 0) <= order
    ]


def hits_points(points: list, text: str) -> int:
    """命中几个要点的关键词。"""
    count = 0
    for point in points:
        if any(k and k in text for k in (point.get("keywords") or [])):
            count += 1
    return count


def attempts_stage(stage: str, text: str) -> bool:
    """学生这句话是否在就这一关表态（用词判断，不看对错）。"""
    words = STAGE_ATTEMPT_WORDS.get(stage, ())
    return any(w in text for w in words)


def current_stage_of(progress: dict, level: str) -> str:
    """当前该答哪一关：按顺序第一个没通过的。"""
    for stage in STAGE_SEQUENCE.get(level, ("辨病",)):
        if not progress.get(stage):
            return stage
    return "已完成"


def judge_stage(case, stage: str, text: str, level: str,
                pulse_done: bool, diff_hit: bool) -> str:
    """判定学生对当前关的表态：pass / wrong / neutral。

    neutral = 没在说这一关（还在问诊、或者跳着答别的关），不计错。
    """
    if not text:
        return "neutral"

    if stage == "辨病":
        return "neutral"      # 辨病由调用方的病名词表判定，这里不重复

    if stage == "平脉":
        if not pulse_done:
            return "neutral"
        points = stage_points(case, "平脉", level)
        if hits_points(points, text) > 0:
            return "pass"
        return "wrong" if attempts_stage("平脉", text) else "neutral"

    if stage == "析证":
        points = stage_points(case, "析证", level)
        if hits_points(points, text) > 0:
            return "pass"
        if attempts_stage("析证", text):
            return "wrong"
        return "neutral"

    if stage == "定治":
        points = stage_points(case, "定治", level)
        if hits_points(points, text) > 0:
            return "pass"
        if attempts_stage("定治", text):
            return "wrong"
        return "neutral"

    return "neutral"


def build_stage_answer(case, stage: str, level: str) -> str:
    """该关的正确答案，用于错满 3 次后由患者公布。"""
    points = stage_points(case, stage, level)
    if points:
        texts = [p.get("text") or "" for p in points if p.get("text")]
        if texts:
            return "；".join(texts[:2])
    return ""
